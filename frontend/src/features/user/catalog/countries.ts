export type CountryOption = { code: string; name: string };

const COUNTRY_SET: ReadonlySet<string> = new Set(COUNTRY_CODES);

export function isCountryCode(code: string): boolean {
  return COUNTRY_SET.has(code);
}

/** Ülkenin o dildeki adı; ad bulunamazsa kodun kendisi. */
export function countryName(code: string, locale: string): string {
  try {
    return new Intl.DisplayNames([locale], { type: "region" }).of(code) ?? code;
  } catch {
    return code;
  }
}

/** Tüm ülkeler, o dilin alfabetik sırasıyla. */
export function countryOptions(locale: string): CountryOption[] {
  const display = new Intl.DisplayNames([locale], { type: "region" });
  const collator = new Intl.Collator(locale);
  return COUNTRY_CODES.map((code) => ({ code, name: display.of(code) ?? code })).sort((a, b) =>
    collator.compare(a.name, b.name)
  );
}
